def apply_litefa_variant(args):
    if args.model_name != "LiteFA_Net":
        return args   # ignore variants for other models

    v = args.LiteFA_Net_variant

    # ───────────────────────────────────────────────────────────────────────────────────────────────
    # 🧩🧠 === LiteFA-Net-n (Nano) === ♻️ down_i = [0, 3, 6] === 🏆71.07% (Cifar100)/p=0.0
    # ───────────────────────────────────────────────────────────────────────────────────────────────
    if v == "n":
        args.state_dim = 70
        args.layers    = 5

    # ─────────────────────────────────────────────────────────────────────────────────────────────────
    # 🧩🧠 === LiteFA-Net-t === ♻️ down_i = [0,5] === 🏆80.66% (Cifar100)/p=0.0
    # ───────────────────────────────────────────────────────────────────────────────────────────────── 
    if v == "t":
        args.state_dim = 160
        args.layers    = 7

    # # ─────────────────────────────────────────────────────────────────────────────────────────────────
    # # === LiteFA-Net-t (optional selection) === ♻️ down_i = [0, 3, 6] === 80.58% (Cifar100)/p=0.0
    # # ───────────────────────────────────────────────────────────────────────────────────────────────── 
    # if v == "t":
    #     args.state_dim = 176
    #     args.layers    = 10

    # ─────────────────────────────────────────────────────────────────────────────────────────────────
    # ⚖️🧠 === LiteFA-Net-S === ♻️ down_i = [0,5] === 🏆82.67% (Cifar100)/p=0.015
    # ─────────────────────────────────────────────────────────────────────────────────────────────────         
    elif v == "S":
        args.state_dim = 192   
        args.layers    = 10    

    # ─────────────────────────────────────────────────────────────────────────────────────────────────
    # 🧩🧠 === LiteFA-Net-M === ♻️ down_i = [0,5] === 🏆83.24 % (Cifar100)/p=0.03
    # ───────────────────────────────────────────────────────────────────────────────────────────────── 
    elif v == "M":
        args.state_dim = 256
        args.layers    = 11   

    # # ─────────────────────────────────────────────────────────────────────────────────────────────────
    # # === LiteFA-Net-M (optional selection) === ♻️ down_i = [0,5] === 83.05% (Cifar100)/p=0.03
    # # ───────────────────────────────────────────────────────────────────────────────────────────────── 
    # elif v == "M":
    #     args.state_dim = 224
    #     args.layers    = 10   

    # ─────────────────────────────────────────────────────────────────────────────────────────────────
    # 🧩🧠 === LiteFA-Net-L === ♻️ down_i = [0,5] === 
    # ───────────────────────────────────────────────────────────────────────────────────────────────── 
    elif v == "L":
        args.state_dim = 384
        args.layers    = 18

    print(f"🚀 Using LiteFA-Net-{v} | state_dim={args.state_dim}, layers={args.layers}")
    
    return args

